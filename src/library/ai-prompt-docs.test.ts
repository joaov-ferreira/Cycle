/**
 * The generated prompt documents (docs/AI_PLAN_PROMPT.md, docs/AI_PLAN_PROMPT.pt-BR.md).
 *
 * `npm run docs:prompt` sets UPDATE_AI_PROMPT_DOCS=1 and runs this file, which then writes the
 * documents. Otherwise a stale document fails the test.
 */
import fs from 'fs';
import path from 'path';
import { buildAiPlanPrompt, type PromptLocale } from './ai-prompt';
import { listExercises } from './index';

const ROOT = path.join(__dirname, '..', '..');
const UPDATE = process.env.UPDATE_AI_PROMPT_DOCS === '1';

const FENCE = '````';

const HEADERS: Record<PromptLocale, { title: string; note: string; steps: string[] }> = {
  en: {
    title: '# CYCLE — AI plan prompt',
    note:
      '> This file is generated by `npm run docs:prompt` from the built-in exercise library. ' +
      'Do not edit it by hand: change the source and run the command again.',
    steps: [
      'Paste the prompt below as the first message of a new chat in any AI assistant.',
      'Add your goal, experience, days per week, equipment, limitations and current loads.',
      'Copy the JSON answer, or save it as a `.json` file, and import it in the app under Plan → New → Import.',
    ],
  },
  'pt-BR': {
    title: '# CYCLE — Prompt para planos com IA',
    note:
      '> Este arquivo é gerado por `npm run docs:prompt` a partir da biblioteca de exercícios do app. ' +
      'Não o edite à mão: altere a origem e rode o comando de novo.',
    steps: [
      'Cole o prompt abaixo como primeira mensagem de um novo chat em qualquer assistente de IA.',
      'Acrescente seus dados: objetivo, experiência, dias por semana, equipamentos, limitações e cargas atuais.',
      'Copie a resposta em JSON, ou salve-a como um arquivo `.json`, e importe-a no app em Periodização → Nova → Importar periodização.',
    ],
  },
};

/** The full Markdown document of one locale, with the prompt of the built-in library. */
function buildPromptDocument(locale: PromptLocale): string {
  const { title, note, steps } = HEADERS[locale];
  const prompt = buildAiPlanPrompt(listExercises(), locale);
  const numbered = steps.map((step, index) => `${index + 1}. ${step}`).join('\n');
  return [title, '', note, '', numbered, '', `${FENCE}text`, prompt, FENCE, ''].join('\n');
}

const DOCUMENTS: { file: string; locale: PromptLocale }[] = [
  { file: 'docs/AI_PLAN_PROMPT.md', locale: 'en' },
  { file: 'docs/AI_PLAN_PROMPT.pt-BR.md', locale: 'pt-BR' },
];

describe('generated AI plan prompt documents', () => {
  it.each(DOCUMENTS)('$file is up to date with the built-in library', ({ file, locale }) => {
    const target = path.join(ROOT, file);
    const expected = buildPromptDocument(locale);
    if (UPDATE) fs.writeFileSync(target, expected, 'utf8');

    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== expected) {
      throw new Error(`${file} is out of date. Run \`npm run docs:prompt\` and commit the result.`);
    }
  });
});
